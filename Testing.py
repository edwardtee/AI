yy = LabelEncoder().fit_transform(yy)

# Split into training (80%) and testing (20%) sets
X_train_raw, X_test_raw, y_train, y_test = train_test_split(XX, yy, test_size=0.2, stratify=yy, random_state=42)
# stratify is used to prevent the model from being trained on a biased sample, it ensure both set got equal % of health and heart disease patients. 
mask = pd.Series(True, index=X_train_raw.index)
for col in ["Age", "Cholesterol", "Blood Pressure", "Heart Rate", "Exercise Hours"]:

    Q1 = X_train_raw[col].quantile(0.25)
    Q3 = X_train_raw[col].quantile(0.75)

    IQR = Q3 - Q1

    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR

    outliers = X_train_raw[(X_train_raw[col] < lower) |
                        (X_train_raw[col] > upper)]

    print(col, len(outliers))

    mask &= (X_train_raw[col] >= lower) & (X_train_raw[col] <= upper)
X_train_raw = X_train_raw[mask]
y_train = y_train[mask]

# To put all the features on the exact same scale to prevent some algo will thing the larger number of other feaure more important
X_train = X_train_raw.copy()
X_test = X_test_raw.copy()
scaler = StandardScaler()
num_cols = ["Age", "Cholesterol", "Blood Pressure", "Heart Rate", "Exercise Hours", "Stress Level", "Blood Sugar"] #, "Blood Pressure", "Heart Rate", "Exercise Hours", "Stress Level", "Blood Sugar"


X_train[num_cols] = scaler.fit_transform(X_train[num_cols])
