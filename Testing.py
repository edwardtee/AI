base_models = [
    ('lr', LogisticRegression(random_state=42, C=0.1)),
    ('knn', KNeighborsClassifier(
        n_neighbors=9,
        weights="uniform",
        metric="euclidean"
    ))
]

#Stacking Classifier, output generated by beta model used as a new input feature to train a meta level.
#Instead of directly using the prediction from beta model againt with actual target.
heart_net = StackingClassifier(
    estimators=base_models,
    final_estimator=LogisticRegression(C=1),
    stack_method='predict_proba',
    cv=5
)

heart_net.fit(X_train, y_train)


y_pred = heart_net.predict(X_test)


# Predicted probabilities for the positive class
y_prob = heart_net.predict_proba(X_test)[:, 1]
auc = roc_auc_score(y_test, y_prob)

precision = precision_score(y_test, y_pred)

recall = recall_score(y_test, y_pred)

f1 = f1_score(y_test, y_pred)

# Print the weights assigned to [LR_probabilities, KNN_probabilities]
print("Meta-estimator weights:", heart_net.final_estimator_.coef_)
print("\n===============================")
print(" Hybrid KNN + LR Results")
print("===============================\n")

print(f"Precision: {precision:.4f}")
print(f"Recall   : {recall:.4f}")
print(f"F1-score : {f1:.4f}")
print(f"ROC-AUC  : {auc:.4f}")
print(
    f"Accuracy: {accuracy_score(y_test, y_pred)*100:.2f}%"
)
